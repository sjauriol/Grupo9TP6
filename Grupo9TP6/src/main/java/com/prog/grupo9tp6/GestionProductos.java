    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarActionPerformed
        int codigo;
        try {
            codigo = Integer.parseInt(txtCodigo.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Ingrese un código numérico para buscar");
            txtCodigo.requestFocus();
            return;
        }

        Producto encontrado = buscarPorCodigo(codigo);
        if (encontrado == null) {
            JOptionPane.showMessageDialog(this, "No existe un producto con ese código");
            return;
        }

        productoSeleccionado = encontrado;
        cargarFormulario(encontrado);
        btnGuardar.setEnabled(false);
        btnActualizar.setEnabled(true);
        btnEliminar.setEnabled(true);
    }//GEN-LAST:event_btnBuscarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        if (productoSeleccionado == null) {
            return;
        }

        int confirmar = JOptionPane.showConfirmDialog(this,
                "¿Eliminar el producto \"" + productoSeleccionado.getDescripcion() + "\"?",
                "Confirmar", JOptionPane.YES_NO_OPTION);

        if (confirmar == JOptionPane.YES_OPTION) {
            VentanaMenu.listaProductos.remove(productoSeleccionado);
            cargarTabla();
            vaciarCampos(pnlDatos);
            estadoInicial();
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        if (!validarCamposVacios(pnlDatos)) {
            JOptionPane.showMessageDialog(this, "Debe completar todos los campos");
            return;
        }

        int codigo;
        try {
            codigo = Integer.parseInt(txtCodigo.getText().trim());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El código debe ser un número entero");
            txtCodigo.requestFocus();
            return;
        }

        if (buscarPorCodigo(codigo) != null) {
            JOptionPane.showMessageDialog(this, "Ya existe un producto con ese código");
            txtCodigo.requestFocus();
            return;
        }

        double precio;
        try {
            precio = Double.parseDouble(txtPrecio.getText().trim().replace(",", "."));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El precio debe ser un número válido");
            txtPrecio.requestFocus();
            return;
        }

        String descripcion = txtDescripcion.getText().trim();
        Categoria rubro = (Categoria) cmbRubro.getSelectedItem();
        int stock = (Integer) spnStock.getValue();

        VentanaMenu.listaProductos.add(new Producto(codigo, descripcion, precio, stock, rubro));

        cargarTabla();
        vaciarCampos(pnlDatos);
        estadoInicial();
        JOptionPane.showMessageDialog(this, "Producto guardado correctamente");
    
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        if (productoSeleccionado == null) {
            return;
        }

        if (!validarCamposVacios(pnlDatos)) {
            JOptionPane.showMessageDialog(this, "Debe completar todos los campos");
            return;
        }

        double precio;
        try {
            precio = Double.parseDouble(txtPrecio.getText().trim().replace(",", "."));
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El precio debe ser un número válido");
            txtPrecio.requestFocus();
            return;
        }

        productoSeleccionado.setDescripcion(txtDescripcion.getText().trim());
        productoSeleccionado.setPrecio(precio);
        productoSeleccionado.setStock((Integer) spnStock.getValue());
        productoSeleccionado.setRubro((Categoria) cmbRubro.getSelectedItem());

        cargarTabla();
        vaciarCampos(pnlDatos);
        estadoInicial();
        JOptionPane.showMessageDialog(this, "Producto actualizado correctamente");
    
    }//GEN-LAST:event_btnActualizarActionPerformed

    private void jtProductosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jtProductosMouseClicked
        int fila = jtProductos.getSelectedRow();
        if (fila < 0) {
            return;
        }

        int codigo = (Integer) modelo.getValueAt(fila, 0);
        Producto p = buscarPorCodigo(codigo);
        if (p == null) {
            return;
        }

        productoSeleccionado = p;
        cargarFormulario(p);
        btnGuardar.setEnabled(false);
        btnActualizar.setEnabled(true);
        btnEliminar.setEnabled(true);
    
    }//GEN-LAST:event_jtProductosMouseClicked

