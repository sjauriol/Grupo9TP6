    private void armarCabecera() {
        modelo.addColumn("Codigo");
        modelo.addColumn("Descripcion");
        modelo.addColumn("Precio");
        modelo.addColumn("Categoria");
        modelo.addColumn("Stock");
        jtProductos.setModel(modelo);
    }

    private void borrarFilas() {
        int filas = jtProductos.getRowCount() - 1;
        for (int f = filas; f >= 0; f--) {
            modelo.removeRow(f);
        }
    }

    private void cargarTabla() {
        Categoria filtro = (Categoria) cmbFiltro.getSelectedItem();
        if (filtro == null) {
            return;
        }

        borrarFilas();
        for (Producto p : VentanaMenu.listaProductos) {
            if (p.getRubro() == filtro) {
                modelo.addRow(new Object[]{
                    p.getCodigo(), p.getDescripcion(), p.getPrecio(),
                    p.getRubro(), p.getStock()
                });
            }
        }
    }

    private void cargarCombo(JComboBox<Categoria> combo) {
        for (Categoria c : Categoria.values()) {
            combo.addItem(c);
        }
    }

    private Producto buscarPorCodigo(int codigo) {
        for (Producto p : VentanaMenu.listaProductos) {
            if (p.getCodigo() == codigo) {
                return p;
            }
        }
        return null;
    }
    // ---------- Validación genérica (sugerida por la cátedra) ----------

    public boolean validarCamposVacios(JPanel jPanel) {
        for (Component c : jPanel.getComponents()) {
            if (c instanceof JTextField) {
                JTextField caja = (JTextField) c;
                if (caja.getText().trim().isEmpty()) {
                    return false;
                }
            }
        }
        return true;
    }

    public void vaciarCampos(JPanel jPanel) {
        for (Component c : jPanel.getComponents()) {
            if (c instanceof JTextField) {
                JTextField caja = (JTextField) c;
                caja.setText("");
            }
            if (c instanceof JComboBox) {
                JComboBox combo = (JComboBox) c;
                combo.setSelectedIndex(0);
            }
        }
        spnStock.setValue(0);
    }
    // ---------- Estados de los botones ----------

    private void estadoInicial() {
        productoSeleccionado = null;
        btnGuardar.setEnabled(false);
        btnActualizar.setEnabled(false);
        btnEliminar.setEnabled(false);
        txtCodigo.setEditable(true);
    }

    private void cargarFormulario(Producto p) {
        txtCodigo.setText(String.valueOf(p.getCodigo()));
        txtDescripcion.setText(p.getDescripcion());
        txtPrecio.setText(String.valueOf(p.getPrecio()));
        cmbRubro.setSelectedItem(p.getRubro());
        spnStock.setValue(p.getStock());
        txtCodigo.setEditable(false); // el código no se modifica en un producto existente
    }
   





   
 
   

  
